import { z } from 'zod';
import { defineWebAction } from '../../define-web-action';
import { readWorkspace, writeWorkspace } from '../../policies';
import { knowledgeVerifiedQuerySchema } from './shared';

const saveUnifiedQuery = defineWebAction({
    id: 'knowledge.saveQuery',
    domain: 'knowledge',
    kind: 'command',
    risk: 'write',
    requiresConfirmation: false,
    permissions: writeWorkspace,
    scopes: ['knowledge:write', 'saved_queries:write'],
    actors: ['user'],
    inputSchema: z.object({
        sourceConnectionId: z.string().min(1),
        knowledgeModelId: z.string().min(1).optional(),
        knowledgeModelIds: z.array(z.string().min(1)).min(1).optional(),
        newModelName: z.string().trim().min(1).max(160).optional(),
        requestId: z.string().uuid(),
        existingQueryId: z.string().min(1).optional(),
        title: z.string().trim().min(1).max(240).optional(),
        sql: z.string().trim().min(1).max(100000).optional(),
        description: z.string().max(4000).nullable().optional(),
        question: z.string().trim().max(4000).optional(),
        edit: z
            .object({
                revision: z.number().int().positive(),
                title: z.string().trim().min(1).max(240),
                sqlText: z.string().trim().min(1).max(100000),
                description: z.string().max(4000).nullable(),
            })
            .optional(),
        collect: z.boolean().optional(),
        folderId: z.string().nullable().optional(),
        knowledgeSourceIds: z.array(z.string()).max(100).optional(),
        sourceType: z.string().max(80).optional(),
        sourceId: z.string().max(240).nullable().optional(),
    }),
    outputSchema: knowledgeVerifiedQuerySchema,
    handler: (ctx, input) => ctx.services.db.knowledge.saveQuery({ ...input, organizationId: ctx.organizationId, userId: ctx.userId }),
});
const listConnectionQueries = defineWebAction({
    id: 'knowledge.listConnectionQueries',
    domain: 'knowledge',
    kind: 'query',
    risk: 'read',
    permissions: readWorkspace,
    scopes: ['knowledge:read'],
    actors: ['user'],
    inputSchema: z.object({ connectionId: z.string().min(1) }),
    outputSchema: z.object({
        queries: z.array(
            z.object({
                id: z.string(),
                title: z.string(),
                sqlText: z.string(),
                description: z.string().nullable(),
                revision: z.number(),
                knowledgeModelId: z.string(),
                queryId: z.string(),
            }),
        ),
    }),
    handler: async (ctx, input) => ({ queries: await ctx.services.db.knowledge.listConnectionQueries({ organizationId: ctx.organizationId, ...input }) }),
});

